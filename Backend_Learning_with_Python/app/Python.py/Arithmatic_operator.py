print(4+8*9) #python follows the BODMAS rule, so it will first multiply 8 and 9, then add 4 to the result.
print(8 **8)

print(9//2) #floor division operator, it will return the largest integer less than or equal to the result of the division.
print(9%2) #modulo operator, it will return the remainder of the division
print(9/2) #normal division operator, it will return the result of the division as a float.

print(9 ** 2) #multiplication operator, it will return the product of the two numbers.
print (5 + 8) #addition operator, it will return the sum of the two numbers.

